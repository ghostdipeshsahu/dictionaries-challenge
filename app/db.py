"""Storage: SQLite (a file, for one server) or Postgres (for Vercel / several servers).

Set DATABASE_URL (or POSTGRES_URL) to a postgres:// URL to use Postgres; otherwise DB_PATH is a SQLite file.
One row per student; mission state is a JSON column (small, read whole, written whole).

Every read-modify-write of a student runs inside `tx()` and reads the row with `by_id(sid, lock=True)`:
on Postgres that is SELECT ... FOR UPDATE, so two servers can never interleave changes to the same student.
"""
import json
import os
import sqlite3
import threading
import time
from contextlib import contextmanager

LOCK = threading.RLock()        # serialises access within one process (SQLite shares one connection)
VERSION = {"n": 0}               # bumped on every write; the teacher stream pushes when it changes
PG = False                       # True when connected to Postgres
_sqlite = None
_pg_url = None
_local = threading.local()      # one Postgres connection per worker thread

SCHEMA_SQLITE = """
CREATE TABLE IF NOT EXISTS students(
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  name TEXT NOT NULL, roll_no TEXT NOT NULL, roll_key TEXT NOT NULL UNIQUE, section TEXT NOT NULL,
  token TEXT UNIQUE, created_at REAL NOT NULL, last_seen REAL, state TEXT NOT NULL, university TEXT NOT NULL DEFAULT '',
  contact TEXT NOT NULL DEFAULT '');
CREATE TABLE IF NOT EXISTS events(
  id INTEGER PRIMARY KEY AUTOINCREMENT, student_id INTEGER NOT NULL, kind TEXT NOT NULL,
  qid TEXT, duration_ms INTEGER, ts REAL NOT NULL);
CREATE INDEX IF NOT EXISTS ev_student ON events(student_id);
CREATE TABLE IF NOT EXISTS teacher_tokens(token TEXT PRIMARY KEY, created_at REAL NOT NULL);
"""

SCHEMA_PG = [
    """CREATE TABLE IF NOT EXISTS students(
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      name TEXT NOT NULL, roll_no TEXT NOT NULL, roll_key TEXT NOT NULL UNIQUE, section TEXT NOT NULL,
      token TEXT UNIQUE, created_at DOUBLE PRECISION NOT NULL, last_seen DOUBLE PRECISION, state TEXT NOT NULL,
      university TEXT NOT NULL DEFAULT '', contact TEXT NOT NULL DEFAULT '')""",
    # databases made before the university and contact fields
    "ALTER TABLE students ADD COLUMN IF NOT EXISTS university TEXT NOT NULL DEFAULT ''",
    "ALTER TABLE students ADD COLUMN IF NOT EXISTS contact TEXT NOT NULL DEFAULT ''",
    """CREATE TABLE IF NOT EXISTS events(
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, student_id BIGINT NOT NULL, kind TEXT NOT NULL,
      qid TEXT, duration_ms INTEGER, ts DOUBLE PRECISION NOT NULL)""",
    "CREATE INDEX IF NOT EXISTS ev_student ON events(student_id)",
    "CREATE TABLE IF NOT EXISTS teacher_tokens(token TEXT PRIMARY KEY, created_at DOUBLE PRECISION NOT NULL)",
]


def connect(target):
    """`target` is a postgres:// URL or a SQLite path (":memory:" for tests)."""
    global PG, _sqlite, _pg_url
    if str(target).startswith(("postgres://", "postgresql://")):
        PG, _pg_url, _sqlite = True, target, None
        _local.conn = None
        _create_pg_schema()
        return
    PG = False
    if target != ":memory:":
        os.makedirs(os.path.dirname(os.path.abspath(target)), exist_ok=True)
    _sqlite = sqlite3.connect(target, check_same_thread=False, isolation_level=None)
    _sqlite.row_factory = sqlite3.Row
    _sqlite.execute("PRAGMA journal_mode=WAL" if target != ":memory:" else "PRAGMA journal_mode=MEMORY")
    _sqlite.executescript(SCHEMA_SQLITE)
    cols = [r["name"] for r in _sqlite.execute("PRAGMA table_info(students)")]
    for col in ("university", "contact"):  # databases made before these fields
        if col not in cols:
            _sqlite.execute(f"ALTER TABLE students ADD COLUMN {col} TEXT NOT NULL DEFAULT ''")


# ---------- Postgres plumbing ----------
def _pg():
    import psycopg
    from psycopg.rows import dict_row
    c = getattr(_local, "conn", None)
    if c is None or c.closed:
        # prepare_threshold=None: works through Neon's / pgbouncer's transaction pooler
        c = psycopg.connect(_pg_url, autocommit=True, row_factory=dict_row, prepare_threshold=None, connect_timeout=10)
        _local.conn = c
    return c


def _create_pg_schema():
    import psycopg
    for attempt in range(3):
        try:
            c = _pg()
            for stmt in SCHEMA_PG:
                c.execute(stmt)
            return
        except psycopg.errors.UniqueViolation:
            time.sleep(0.2 * (attempt + 1))  # two servers creating the tables at once
        except psycopg.OperationalError:
            _local.conn = None
            if attempt == 2:
                raise


def _run(sql, args=(), fetch=None):
    """Run one statement. fetch: None, 'one' or 'all'. Postgres retries once on a dropped connection."""
    if not PG:
        cur = _sqlite.execute(sql, args)
        return cur.fetchone() if fetch == "one" else cur.fetchall() if fetch == "all" else cur
    import psycopg
    sql = sql.replace("?", "%s")
    for attempt in range(2):
        c = _pg()
        try:
            cur = c.execute(sql, args)
            return cur.fetchone() if fetch == "one" else cur.fetchall() if fetch == "all" else cur
        except psycopg.OperationalError:
            if attempt or getattr(_local, "in_tx", False):
                raise
            _local.conn = None  # stale pooled connection: reconnect and retry once


@contextmanager
def tx():
    """A transaction (Postgres) / the process lock (SQLite). Nest freely.

    Postgres needs no process lock: each thread has its own connection, and by_id(lock=True) locks the student's
    row, so requests for different students run side by side (a process-wide lock queued a whole class)."""
    if not PG:
        with LOCK:
            yield
        return
    if getattr(_local, "in_tx", False):
        yield
        return
    c = _pg()
    _local.in_tx = True
    try:
        with c.transaction():
            yield
    finally:
        _local.in_tx = False


def bump():
    VERSION["n"] += 1


# ---------- students ----------
def roll_key(roll):
    return " ".join(str(roll).split()).upper()


def row_to_student(r):
    if not r:
        return None
    d = dict(r)
    d["state"] = json.loads(d["state"])
    return d


def by_token(token):
    if not token:
        return None
    return row_to_student(_run("SELECT * FROM students WHERE token=?", (token,), "one"))


def by_roll(roll):
    return row_to_student(_run("SELECT * FROM students WHERE roll_key=?", (roll_key(roll),), "one"))


def by_id(sid, lock=False):
    """lock=True (inside tx) holds the row until the transaction ends, on Postgres."""
    sql = "SELECT * FROM students WHERE id=?" + (" FOR UPDATE" if lock and PG else "")
    return row_to_student(_run(sql, (sid,), "one"))


def all_students(section=None):
    if section:
        rows = _run("SELECT * FROM students WHERE section=? ORDER BY id", (section,), "all")
    else:
        rows = _run("SELECT * FROM students ORDER BY id", (), "all")
    return [row_to_student(r) for r in rows]


def section_key(section):
    """Sections are typed by the students: "s-001", "S 001" and "S001" are the same section."""
    return "".join(ch for ch in str(section).upper() if ch.isalnum())


def known_section(section):
    """The spelling already in use for this section (so one section is not split by how it was typed), else None."""
    key = section_key(section)
    for r in _run("SELECT DISTINCT section FROM students", (), "all"):
        if section_key(r["section"]) == key:
            return r["section"]
    return None


def sections():
    return sorted({r["section"] for r in _run("SELECT DISTINCT section FROM students", (), "all")}, key=str.casefold)


def insert_student(name, roll, section, token, state, university="", contact=""):
    now = time.time()
    r = _run("INSERT INTO students(name, roll_no, roll_key, section, token, created_at, last_seen, state, university, contact) "
             "VALUES(?,?,?,?,?,?,?,?,?,?) RETURNING id",
             (name, roll, roll_key(roll), section, token, now, now, json.dumps(state), university, contact), "one")
    bump()
    return r["id"]


def set_token(sid, token, seen=True):
    _run("UPDATE students SET token=?, last_seen=? WHERE id=?", (token, time.time() if seen else None, sid))
    bump()


def fill_profile(sid, university, contact):
    """Students who signed up before these fields: fill the ones still empty."""
    _run("UPDATE students SET university=CASE WHEN university='' THEN ? ELSE university END, "
         "contact=CASE WHEN contact='' THEN ? ELSE contact END WHERE id=?", (university, contact, sid))
    bump()


def touch(sid):
    _run("UPDATE students SET last_seen=? WHERE id=?", (time.time(), sid))
    bump()


def save_state(sid, state, seen=True):
    """seen=False when someone else (the teacher) changes the state: it must not mark the student as online."""
    if seen:
        _run("UPDATE students SET state=?, last_seen=? WHERE id=?", (json.dumps(state), time.time(), sid))
    else:
        _run("UPDATE students SET state=? WHERE id=?", (json.dumps(state), sid))
    bump()


def reset_state(sid, state):
    _run("UPDATE students SET state=? WHERE id=?", (json.dumps(state), sid))
    _run("DELETE FROM events WHERE student_id=?", (sid,))
    bump()


def delete_student(sid):
    _run("DELETE FROM students WHERE id=?", (sid,))
    _run("DELETE FROM events WHERE student_id=?", (sid,))
    bump()


def log_event(sid, kind, qid=None, duration_ms=None):
    _run("INSERT INTO events(student_id, kind, qid, duration_ms, ts) VALUES(?,?,?,?,?)",
         (sid, kind, qid, duration_ms, time.time()))


# ---------- teacher sessions ----------
def add_teacher_token(token):
    _run("INSERT INTO teacher_tokens(token, created_at) VALUES(?,?)", (token, time.time()))


def teacher_token_ok(token, max_age):
    if not token:
        return False
    r = _run("SELECT created_at FROM teacher_tokens WHERE token=?", (token,), "one")
    return bool(r) and time.time() - r["created_at"] < max_age


def drop_teacher_token(token):
    _run("DELETE FROM teacher_tokens WHERE token=?", (token,))
